#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""公式常量注入（T21 阶段三 / P2-10）
==================================
把 index.html 里的 JS 公式常量 K 改为**由 C# 单一事实源生成**，消除「两侧人工
同步」这一类漂移：src/AstralPath.Core/Formula/FormulaConstants.cs 是唯一来源。

- 21 项数值直映射（W.e / floor / stab0 / … / saleMinAtt）从 C# 常量读出；
- SpacingOffsets 是 JS 侧独有的计划间隔偏移，保留字面量并在注释中说明；
- 生成区写入 index.html，--check 只校验（CI / verify_all 用）。

用法：
    python scripts/gen_formula_constants.py            # 生成并写入
    python scripts/gen_formula_constants.py --check    # 只校验
退出码：0 = 一致/已生成；1 = 漂移
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from verify_constants import DIRECT_MAP  # noqa: E402  复用对拍用的映射表

CS = ROOT / "src" / "AstralPath.Core" / "Formula" / "FormulaConstants.cs"
HTML = ROOT / "deploy" / "monolith-web" / "index.html"

BEGIN = "/* AP:BEGIN formula-constants · generated by scripts/gen_formula_constants.py · DO NOT EDIT */"
END = "/* AP:END formula-constants */"

# JS 侧独有的常量（C# 无对应声明）：计划间隔偏移 [0,2,6] 天
JS_ONLY = 'SpacingOffsets:[0,2,6]'


def parse_cs() -> dict:
    vals = {}
    for m in re.finditer(r"public const (?:double|decimal|int|float)\s+(\w+)\s*=\s*([-\d.]+)(?:[mfd])?\s*;",
                         CS.read_text(encoding="utf-8")):
        vals[m.group(1)] = float(m.group(2))
    return vals


def fmt(v: float) -> str:
    if v == int(v):
        return str(int(v))
    s = ("%.10f" % v).rstrip("0").rstrip(".")
    if s.startswith("0."):
        s = "." + s[2:]
    return s


def build_js(vals: dict) -> str:
    parts = []
    for js_path, cs_name, _ in DIRECT_MAP:
        if cs_name not in vals:
            raise SystemExit(f"C# 缺少常量 {cs_name}（JS 字段 {js_path}）")
        v = vals[cs_name]
        if js_path.startswith("W."):
            continue
        parts.append(f"{js_path}:{fmt(v)}")
    w = "W:{e:%s,r:%s,p:%s}" % (fmt(vals["WEmpirical"]), fmt(vals["WRetention"]), fmt(vals["WPrereq"]))
    return "const K={%s,%s,%s};" % (w, ",".join(parts), JS_ONLY)


def main() -> int:
    check = "--check" in sys.argv[1:]
    vals = parse_cs()
    js = build_js(vals)
    want = BEGIN + "\n" + js + "\n" + END
    html = HTML.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in html else "\n"

    has_region = BEGIN in html and END in html
    if has_region:
        i = html.index(BEGIN)
        j = html.index(END) + len(END)
        have = html[i:j]
        if check:
            if have.replace("\r\n", "\n") != want.replace("\r\n", "\n"):
                print("FAILED: 生成区与 C# 常量不一致，请跑 python scripts/gen_formula_constants.py")
                return 1
            print(f"ALL GREEN · 公式常量生成区与 C# 一致（{len(DIRECT_MAP)} 项直映射 + SpacingOffsets）")
            return 0
        html = html[:i] + want + html[j:]
    else:
        m = re.search(r"^const K=\{.*?\};\s*$", html, re.M | re.S)
        if not m:
            print("[失败] 未找到 const K={...} 声明")
            return 1
        if check:
            print("FAILED: 尚未建立生成区，请跑 python scripts/gen_formula_constants.py")
            return 1
        indent = ""
        html = html[:m.start()] + want.replace("\n", nl) + html[m.end():]

    HTML.write_text(html, encoding="utf-8")
    print(f"[OK] 已写入生成区：{len(DIRECT_MAP)} 项直映射 + {JS_ONLY}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
